def _safe_float(x, default=0.0):
    return float(x) if x not in (None, "") else default


def _seed_level_from_rows(rows: list[dict], seed: int, bank: str = BANK) -> dict:
    sub = [r for r in rows if int(r["seed"]) == seed and r["bank"] == bank]
    if len(sub) != N_EPISODES_EXPECTED:
        raise ValueError(f"seed {seed}: expected {N_EPISODES_EXPECTED} episodes, got {len(sub)}")
    completion = [float(r["completion"]) for r in sub]
    collision = [float(r["collision"]) for r in sub]
    umin = [float(r["min_U"]) for r in sub]
    ginis = [_safe_float(r["gini"], 0.0) for r in sub]  # gini undefined (empty) only when all-4-utilities==0; treat as 0 (perfectly equal, all-zero)
    for name, vals in (("completion", completion), ("collision", collision), ("min_U", umin), ("gini", ginis)):
        if not all(math.isfinite(v) for v in vals):
            raise ValueError(f"seed {seed}: non-finite value(s) in {name}")
    return {
        "completion": float(np.mean(completion)),
        "collision": float(np.mean(collision)),
        "U_min": float(np.mean(umin)),
        "gini": float(np.mean(ginis)),
    }


def load_original() -> dict:
    with open(ORIGINAL_BASELINE_CSV, encoding="utf-8") as f:
        baseline_rows = list(csv.DictReader(f))
    with open(ORIGINAL_WELFARE_CSV, encoding="utf-8") as f:
        welfare_rows = list(csv.DictReader(f))

    out = {cond: {} for cond in CONDITIONS}
    for seed in SEEDS_12:
        out["baseline"][seed] = _seed_level_from_rows(
            [r for r in baseline_rows if r["condition"] == "taskonly"], seed
        )
        for cond in WELFARE_CONDITIONS:
            out[cond][seed] = _seed_level_from_rows(
                [r for r in welfare_rows if r["condition"] == cond], seed
            )
    return out


def load_wsc() -> dict:
    with open(WSC_V2_CSV, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    out = {cond: {} for cond in CONDITIONS}
    seen = set()
    for cond in CONDITIONS:
        cond_rows = [r for r in rows if r["condition"] == cond]
        for seed in SEEDS_12:
            key = (cond, seed)
            if key in seen:
                raise ValueError(f"duplicate seed-condition row detected: {key}")
            seen.add(key)
            out[cond][seed] = _seed_level_from_rows(cond_rows, seed)
    if len(seen) != len(CONDITIONS) * len(SEEDS_12):
        raise ValueError("did not find exactly 12 seeds x 4 conditions in WSC v2 CSV")
    return out


