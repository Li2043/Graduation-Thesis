    log(f"bootstrap             : n_boot={N_BOOT} rng_seed={BOOT_RNG_SEED} CI=percentile[2.5,97.5] two-sided p")

    run_audit = audit_wsc_v2_runs()
    log(f"\nWSC v2 run audit: {run_audit['n_v2_checked_ok']}/{run_audit['n_v2_registry_rows']} rows OK, "
        f"{run_audit['n_v2_problems']} problems")
    if run_audit["n_v2_problems"] > 0:
        for p in run_audit["problems"]:
            log(f"  PROBLEM: {p}")
        raise SystemExit("FATAL: WSC v2 run audit found problems -- refusing to proceed with formal analysis.")
    if not run_audit["v1_isolation_ok"]:
        raise SystemExit("FATAL: v1 invalid registry isolation check failed.")
    log("v1 invalid registry isolation: OK (48/48 rows marked INVALID_PRE_FIX_COLUMN_MAPPING, untouched)")

    orig = load_original()
    wsc = load_wsc()
    seed_level_rows = build_seed_level_table(orig, wsc)

    # reproducibility guards
    assert len(seed_level_rows) == len(SEEDS_12) * len(CONDITIONS)
    seen_keys = set()
    for r in seed_level_rows:
        key = (r["seed"], r["condition"])
        if key in seen_keys:
            raise ValueError(f"duplicate seed-condition row in seed-level table: {key}")
        seen_keys.add(key)
    for r in seed_level_rows:
        for k, v in r.items():
            if isinstance(v, float) and not math.isfinite(v):
                raise ValueError(f"non-finite value in seed-level row {r['seed']}/{r['condition']}: {k}={v}")

    seed_level_csv = OUT_DIR / "wsc_v2_formal_seed_level.csv"
    fieldnames: list[str] = []
    for r in seed_level_rows:
        for k in r.keys():
            if k not in fieldnames:
                fieldnames.append(k)
    for r in seed_level_rows:
        for k in fieldnames:
            r.setdefault(k, "")
    with open(seed_level_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(seed_level_rows)
    log(f"\nwrote {seed_level_csv}  ({len(seed_level_rows)} rows)")

    # --- Primary n=12 fairness analysis ---
    primary = fairness_analysis(seed_level_rows, SEEDS_12, "primary_n12")
    sens_seeds = [s for s in SEEDS_12 if s != SENSITIVITY_EXCLUDE_SEED]
    sensitivity = fairness_analysis(seed_level_rows, sens_seeds, "sensitivity_n11_excl_910102")

    log("\n" + "=" * 78)
    log("PRIMARY (n=12) fairness interaction results")
    log("=" * 78)
    for outcome in ("U_min", "Gini"):
        log(f"\n--- {outcome} interaction ---")
        for cond in WELFARE_CONDITIONS:
            d = primary["outcomes"][outcome][cond]
            log(f"  {cond.upper():8} mean={d['mean']:+.4f} median={d['median']:+.4f} sd={d['sd']:.4f} "
                f"pos/neg/zero={d['n_positive']}/{d['n_negative']}/{d['n_zero']} "
                f"CI95=[{d['CI95_low']:+.4f},{d['CI95_high']:+.4f}] raw_p={d['raw_p_bootstrap_two_sided']:.4f} "
                f"holm_p={d['holm_adjusted_p']:.4f} reject={d['reject_at_alpha05']}")

    log("\n" + "=" * 78)
    log("SENSITIVITY (n=11, excl. seed 910102) fairness interaction results")
    log("=" * 78)
    for outcome in ("U_min", "Gini"):
        log(f"\n--- {outcome} interaction ---")
        for cond in WELFARE_CONDITIONS:
            d = sensitivity["outcomes"][outcome][cond]
            log(f"  {cond.upper():8} mean={d['mean']:+.4f} CI95=[{d['CI95_low']:+.4f},{d['CI95_high']:+.4f}] "
                f"holm_p={d['holm_adjusted_p']:.4f} reject={d['reject_at_alpha05']}")

    # fairness summary CSV
    fairness_summary_rows = []
    for label, res in (("primary_n12", primary), ("sensitivity_n11_excl_910102", sensitivity)):
        for outcome in ("U_min", "Gini"):
            for cond in WELFARE_CONDITIONS:
                d = res["outcomes"][outcome][cond]
                fairness_summary_rows.append({
                    "analysis": label, "outcome": outcome, "condition": cond, "n": d["n"],
                    "mean": round(d["mean"], 6), "median": round(d["median"], 6), "sd": round(d["sd"], 6),
                    "n_positive": d["n_positive"], "n_negative": d["n_negative"], "n_zero": d["n_zero"],
                    "CI95_low": round(d["CI95_low"], 6), "CI95_high": round(d["CI95_high"], 6),
                    "raw_p_bootstrap": round(d["raw_p_bootstrap_two_sided"], 6),
                    "holm_adjusted_p": round(d["holm_adjusted_p"], 6),
                    "reject_at_alpha05": d["reject_at_alpha05"],
                })
    fairness_csv = OUT_DIR / "wsc_v2_formal_fairness_summary.csv"
    with open(fairness_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(fairness_summary_rows[0].keys()))
        w.writeheader(); w.writerows(fairness_summary_rows)
    log(f"\nwrote {fairness_csv}")

    # sensitivity side-by-side CSV
    sens_rows = []
    for outcome in ("U_min", "Gini"):
        for cond in WELFARE_CONDITIONS:
            p12 = primary["outcomes"][outcome][cond]
            p11 = sensitivity["outcomes"][outcome][cond]
            qual_p12 = "positive" if p12["mean"] > 0 else ("negative" if p12["mean"] < 0 else "zero")
            qual_p11 = "positive" if p11["mean"] > 0 else ("negative" if p11["mean"] < 0 else "zero")
            sens_rows.append({
                "outcome": outcome, "condition": cond,
                "n12_mean": round(p12["mean"], 6), "n12_CI_low": round(p12["CI95_low"], 6), "n12_CI_high": round(p12["CI95_high"], 6),
                "n11_mean": round(p11["mean"], 6), "n11_CI_low": round(p11["CI95_low"], 6), "n11_CI_high": round(p11["CI95_high"], 6),
                "point_estimate_change": round(p11["mean"] - p12["mean"], 6),
                "qualitative_direction_n12": qual_p12, "qualitative_direction_n11": qual_p11,
                "direction_changed": qual_p12 != qual_p11,
            })
    sens_csv = OUT_DIR / "wsc_v2_formal_sensitivity_910102.csv"
    with open(sens_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(sens_rows[0].keys()))
        w.writeheader(); w.writerows(sens_rows)
    log(f"wrote {sens_csv}")

    # leave-one-out
    loo_rows = leave_one_seed_out(seed_level_rows)
    loo_csv = OUT_DIR / "wsc_v2_leave_one_seed_out.csv"
    with open(loo_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(loo_rows[0].keys()))
        w.writeheader(); w.writerows(loo_rows)
    log(f"wrote {loo_csv}")

    # safety analysis
    safety = safety_analysis(seed_level_rows)
    log("\n" + "=" * 78)
    log("SAFETY / TASK-PERFORMANCE analysis (descriptive, paired, n=12)")
    log("=" * 78)
    safety_rows = []
    for metric in ("completion", "collision"):
        for cond in CONDITIONS:
            d = safety[metric][cond]
            log(f"  Delta_{metric:10} {cond:8} mean={d['mean_paired_diff']:+.4f} CI95=[{d['CI95_low']:+.4f},{d['CI95_high']:+.4f}] "
                f"pos/neg={d['n_positive']}/{d['n_negative']} raw_p={d['raw_p_bootstrap_two_sided']:.4f}")
            safety_rows.append({
                "metric": metric, "condition": cond, "n": d["n"],
                "mean_paired_diff_wsc_minus_orig": round(d["mean_paired_diff"], 6),
                "median_paired_diff": round(d["median_paired_diff"], 6), "sd": round(d["sd"], 6),
                "n_positive": d["n_positive"], "n_negative": d["n_negative"], "n_zero": d["n_zero"],
                "CI95_low": round(d["CI95_low"], 6), "CI95_high": round(d["CI95_high"], 6),
                "raw_p_bootstrap_two_sided": round(d["raw_p_bootstrap_two_sided"], 6),
                "note": d["note"],
            })
    safety_csv = OUT_DIR / "wsc_v2_formal_safety_summary.csv"
    with open(safety_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(safety_rows[0].keys()))
        w.writeheader(); w.writerows(safety_rows)
    log(f"\nwrote {safety_csv}")

    heterogeneity = heterogeneity_metrics(seed_level_rows)

    provenance = build_provenance(run_audit)
    prov_path = OUT_DIR / "wsc_v2_data_provenance.json"
    with open(prov_path, "w", encoding="utf-8") as f:
        json.dump(provenance, f, indent=2, default=str)
    log(f"wrote {prov_path}")

    bootstrap_results = {
        "config": {
            "seeds_12": SEEDS_12, "sensitivity_excluded_seed": SENSITIVITY_EXCLUDE_SEED,
            "n_boot": N_BOOT, "rng_seed": BOOT_RNG_SEED, "alpha": ALPHA,
            "welfare_conditions": WELFARE_CONDITIONS, "bank": BANK,
        },
        "primary_n12": primary,
        "sensitivity_n11": sensitivity,
        "safety": safety,
        "heterogeneity": heterogeneity,
        "run_audit": run_audit,
    }
    boot_json_path = OUT_DIR / "wsc_v2_formal_bootstrap_results.json"
    with open(boot_json_path, "w", encoding="utf-8") as f:
        json.dump(bootstrap_results, f, indent=2, default=str)
    log(f"wrote {boot_json_path}")

    with open(OUT_DIR / "wsc_v2_formal_analysis_log.txt", "w", encoding="utf-8") as f:
        f.write("\n".join(LOG))

    log("\nDONE.")
    return 0


