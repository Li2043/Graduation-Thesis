def main() -> int:
    log("=" * 78)
    log("WSC v2 FORMAL EVALUATION -- evaluation-only, no training changes")
    log("=" * 78)
    log(f"Original baseline CSV : {ORIGINAL_BASELINE_CSV}")
    log(f"Original welfare CSV  : {ORIGINAL_WELFARE_CSV}")
    log(f"WSC v2 evaluation CSV : {WSC_V2_CSV}")
