# Safety analysis (Section 10) -- descriptive, paired bootstrap, NOT Holm-corrected
# (no established formal family for this exact comparison in the project's
# prior protocol -- see module docstring / report Section C for rationale)
# ============================================================================
def safety_analysis(seed_level_rows: list[dict]) -> dict:
    result = {}
    for metric, key in (("completion", "delta_completion_wsc_minus_orig"), ("collision", "delta_collision_wsc_minus_orig")):
        result[metric] = {}
        for cond in CONDITIONS:
            vals = np.array([r[key] for r in seed_level_rows if r["condition"] == cond])
            assert len(vals) == 12
            est, lo, hi, boot = bootstrap_ci_paired(vals, n_boot=N_BOOT, rng_seed=BOOT_RNG_SEED)
            p = bootstrap_p_value(boot)
            result[metric][cond] = {
                "n": 12, "mean_paired_diff": est, "median_paired_diff": float(np.median(vals)),
                "sd": float(np.std(vals, ddof=1)), "n_positive": int(np.sum(vals > 0)),
                "n_negative": int(np.sum(vals < 0)), "n_zero": int(np.sum(vals == 0)),
                "CI95_low": lo, "CI95_high": hi, "raw_p_bootstrap_two_sided": p,
                "note": "descriptive/safety -- not part of a pre-specified Holm-corrected confirmatory family",
                "seed_values": {int(r["seed"]): float(r[key]) for r in seed_level_rows if r["condition"] == cond},
            }
    return result


def heterogeneity_metrics(seed_level_rows: list[dict]) -> dict:
    out = {}
    for metric, key in (("delta_completion", "delta_completion_wsc_minus_orig"), ("delta_collision", "delta_collision_wsc_minus_orig")):
        out[metric] = {}
        for cond in CONDITIONS:
            vals = np.array([r[key] for r in seed_level_rows if r["condition"] == cond])
            q1, q3 = np.percentile(vals, [25, 75])
            out[metric][cond] = {
                "sd": float(np.std(vals, ddof=1)), "min": float(np.min(vals)), "max": float(np.max(vals)),
                "iqr": float(q3 - q1), "n_positive": int(np.sum(vals > 0)), "n_negative": int(np.sum(vals < 0)),
            }
    for outcome, key in (("I_Umin", "I_Umin"), ("I_Gini", "I_Gini")):
        out[outcome] = {}
        for cond in WELFARE_CONDITIONS:
            vals = np.array([r[key] for r in seed_level_rows if r["condition"] == cond])
            q1, q3 = np.percentile(vals, [25, 75])
            out[outcome][cond] = {
                "sd": float(np.std(vals, ddof=1)), "min": float(np.min(vals)), "max": float(np.max(vals)),
                "iqr": float(q3 - q1), "n_positive": int(np.sum(vals > 0)), "n_negative": int(np.sum(vals < 0)),
            }
    return out


