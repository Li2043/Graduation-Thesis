def build_seed_level_table(orig: dict, wsc: dict) -> list[dict]:
    rows = []
    for seed in SEEDS_12:
        for cond in CONDITIONS:
            o = orig[cond][seed]
            w = wsc[cond][seed]
            row = {
                "seed": seed, "condition": cond,
                "orig_completion": o["completion"], "orig_collision": o["collision"],
                "orig_U_min": o["U_min"], "orig_gini": o["gini"],
                "wsc_completion": w["completion"], "wsc_collision": w["collision"],
                "wsc_U_min": w["U_min"], "wsc_gini": w["gini"],
                "delta_completion_wsc_minus_orig": w["completion"] - o["completion"],
                "delta_collision_wsc_minus_orig": w["collision"] - o["collision"],
            }
            if cond in WELFARE_CONDITIONS:
                bo = orig["baseline"][seed]
                bw = wsc["baseline"][seed]
                orig_contrast_umin = o["U_min"] - bo["U_min"]
                wsc_contrast_umin = w["U_min"] - bw["U_min"]
                orig_contrast_gini = o["gini"] - bo["gini"]
                wsc_contrast_gini = w["gini"] - bw["gini"]
                row.update({
                    "orig_contrast_Umin_vs_baseline": orig_contrast_umin,
                    "wsc_contrast_Umin_vs_baseline": wsc_contrast_umin,
                    "I_Umin": wsc_contrast_umin - orig_contrast_umin,
                    "orig_contrast_gini_vs_baseline": orig_contrast_gini,
                    "wsc_contrast_gini_vs_baseline": wsc_contrast_gini,
                    "I_Gini": wsc_contrast_gini - orig_contrast_gini,
                })
            rows.append(row)
    return rows


