def audit_wsc_v2_runs() -> dict:
    with open(WSC_V2_REGISTRY, encoding="utf-8") as f:
        reg = list(csv.DictReader(f))
    assert len(reg) == 48, f"expected 48 WSC v2 registry rows, got {len(reg)}"

    problems = []
    checked = 0
    for r in reg:
        seed, cond, run_id = r["seed"], r["condition"], r["run_id"]
        if r["status"] != "COMPLETED" or r["exit_code"] != "0":
            problems.append(f"{run_id}: status={r['status']} exit_code={r['exit_code']}")
            continue
        src = r["source_checkpoint"]
        if "wsc" in src.lower() or str(INVALID_V1_ROOT) in src:
            problems.append(f"{run_id}: source checkpoint looks WSC-derived or pre-fix invalid: {src}")
        if "ckpt_step_1200000.pt" not in src:
            problems.append(f"{run_id}: source checkpoint is not step 1,200,000: {src}")
        out_dir = Path(r["output_dir"])
        if WSC_OUTPUT_ROOT.name not in str(out_dir) or str(INVALID_V1_ROOT) == str(out_dir.parent):
            problems.append(f"{run_id}: output_dir does not look like the v2 root: {out_dir}")
        stage = f"Formal_{cond}_WSC_v2"
        ckpt_dir = out_dir / f"seed_{seed}_{stage}"
        for step in ENSEMBLE_WINDOW:
            if not (ckpt_dir / f"ckpt_step_{step}.pt").exists():
                problems.append(f"{run_id}: missing ensemble checkpoint step {step}")
        checked += 1

    with open(V1_INVALID_REGISTRY, encoding="utf-8") as f:
        v1_reg = list(csv.DictReader(f))
    n_invalid_marked = sum(1 for r in v1_reg if r["status"] == "INVALID_PRE_FIX_COLUMN_MAPPING")

    result = {
        "n_v2_registry_rows": len(reg),
        "n_v2_checked_ok": checked,
        "n_v2_problems": len(problems),
        "problems": problems,
        "n_v1_invalid_registry_rows": len(v1_reg),
        "n_v1_marked_invalid": n_invalid_marked,
        "v1_isolation_ok": n_invalid_marked == 48 and len(v1_reg) == 48,
    }
    return result


