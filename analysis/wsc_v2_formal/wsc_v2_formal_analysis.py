# Fairness interaction formal analysis (Section 7)
# ============================================================================
def fairness_analysis(seed_level_rows: list[dict], seed_set: list[int], label: str) -> dict:
    n = len(seed_set)
    result = {"n": n, "seed_set": seed_set, "label": label, "outcomes": {}}
    for outcome, key in (("U_min", "I_Umin"), ("Gini", "I_Gini")):
        raw_p = {}
        est_ci = {}
        per_cond_vals = {}
        for cond in WELFARE_CONDITIONS:
            vals = np.array([
                r[key] for r in seed_level_rows
                if r["condition"] == cond and r["seed"] in seed_set
            ])
            assert len(vals) == n, (outcome, cond, len(vals), n)
            est, lo, hi, boot = bootstrap_ci_paired(vals, n_boot=N_BOOT, rng_seed=BOOT_RNG_SEED)
            p = bootstrap_p_value(boot)
            raw_p[cond] = p
            est_ci[cond] = (est, lo, hi)
            per_cond_vals[cond] = vals.tolist()
        order = WELFARE_CONDITIONS  # fixed order: mean, ggi, maximin (m=3 Holm family)
        pvals = [raw_p[c] for c in order]
        adj = holm_correction(pvals)
        outcome_result = {}
        for cond, p, a in zip(order, pvals, adj):
            est, lo, hi = est_ci[cond]
            vals = np.array(per_cond_vals[cond])
            outcome_result[cond] = {
                "n": n, "mean": est, "median": float(np.median(vals)), "sd": float(np.std(vals, ddof=1)),
                "n_positive": int(np.sum(vals > 0)), "n_negative": int(np.sum(vals < 0)), "n_zero": int(np.sum(vals == 0)),
                "CI95_low": lo, "CI95_high": hi, "raw_p_bootstrap_two_sided": p,
                "holm_adjusted_p": a, "reject_at_alpha05": bool(a < ALPHA),
                "seed_values": {int(s): float(v) for s, v in zip(seed_set, vals)},
            }
        result["outcomes"][outcome] = outcome_result
    return result


def leave_one_seed_out(seed_level_rows: list[dict]) -> list[dict]:
    rows = []
    for outcome, key in (("U_min", "I_Umin"), ("Gini", "I_Gini")):
        for cond in WELFARE_CONDITIONS:
            full_vals = {r["seed"]: r[key] for r in seed_level_rows if r["condition"] == cond}
            full_est = float(np.mean(list(full_vals.values())))
            loo_ests = {}
            for excl in SEEDS_12:
                remaining = [v for s, v in full_vals.items() if s != excl]
                loo_ests[excl] = float(np.mean(remaining))
            shifts = {s: loo_ests[s] - full_est for s in SEEDS_12}
            max_shift_seed = max(shifts, key=lambda s: abs(shifts[s]))
            for seed in SEEDS_12:
                rows.append({
                    "outcome": outcome, "condition": cond, "excluded_seed": seed,
                    "leave_one_out_estimate": loo_ests[seed],
                    "full_n12_estimate": full_est,
                    "shift_from_full": shifts[seed],
                    "is_largest_shift_seed": seed == max_shift_seed,
                })
    return rows


